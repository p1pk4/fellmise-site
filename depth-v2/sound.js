/* Звук маршрута: подписка на принятый Audio 1, а не второй движок.
 *
 * Сам движок берётся из /proto/audio.js как есть — ни одной его строки здесь
 * не переписано и не скопировано. Ассеты те же самые: /assets/topdown/audio.json
 * и пять эмбиентов с четырьмя SFX переходов из /assets/audio/. Ничего не
 * генерируется и не дублируется.
 *
 * Движок специально устроен так, что карту биомов и разметку переходов ему
 * передают снаружи. Ему всё равно, чем измеряется путь: уровни — чистая
 * функция одной координаты, которую хост присылает каждый кадр. Поэтому здесь
 * нужен только переводчик между прогрессом маршрута и его системой координат.
 *
 * Маршрут /depth-v2/ ведётся прогрессом 0..1, а /proto/ — метрами камеры от 0
 * до -662. Прогресс переводится в ту же шкалу метров намеренно: в движке есть
 * модульная константа SFX_REARM_M = 8 метров, гистерезис для SFX. В своей
 * шкале она даёт перевзвод на 1.2% маршрута — именно столько, чтобы дрожание
 * колеса у границы не выстреливало звук переходa повторно. Если бы прогресс
 * уходил в движок как 0..1, восемь единиц гистерезиса накрыли бы весь путь и
 * SFX не прозвучал бы ни разу.
 *
 * Полосы смешивания посажены на настоящие окна раскрытия принятой хореографии,
 * а не придуманы отдельно: звук биома начинает подмешиваться ровно тогда, когда
 * следующая сцена проступает в кадре. Хореографию для этого трогать не нужно —
 * зависимость односторонняя, звук подписывается на маршрут.
 */
import { createAudio } from '../proto/audio.js';

const ROUTE_M = 662;                 // длина маршрута в шкале движка
const z = (p) => -ROUTE_M * p;

/* Полосы взяты из журнала раскрытий: village 0.093, forest 0.248, mine 0.407,
   home 0.721-0.805. Порог и ядро — один биом spirit, как и в Audio 1, поэтому
   между ними нет ни смены эмбиента, ни SFX: это один слой мира. */
const BANDS = [
  { from: 'village', to: 'forest', blend: [0.09, 0.17], anchor: 0.13 },
  { from: 'forest',  to: 'mine',   blend: [0.25, 0.33], anchor: 0.29 },
  { from: 'mine',    to: 'spirit', blend: [0.41, 0.49], anchor: 0.45 },
  { from: 'spirit',  to: 'home',   blend: [0.72, 0.84], anchor: 0.78 },
];

const PRESENTATION = {
  biomes: [{ id: 'village' }, { id: 'forest' }, { id: 'mine' }, { id: 'spirit' }, { id: 'home' }],
  transitions: BANDS.map((b) => ({
    from: b.from, to: b.to,
    blend_z: [z(b.blend[0]), z(b.blend[1])],
    anchor_z: z(b.anchor),
  })),
};

/* Та же формула, что смешивает грунт в /proto/: сумма сглаженных ступеней даёт
   непрерывное число 0..4 по списку биомов, а его дробная часть и есть позиция
   кроссфейда. Одна карта биомов на картинку и на звук. */
function biomeAt(zz) {
  let b = 0;
  for (const t of PRESENTATION.transitions) {
    const [z0, z1] = t.blend_z;
    const u = Math.min(Math.max((z0 - zz) / (z0 - z1), 0), 1);
    b += u * u * (3 - 2 * u);
  }
  return b;
}

export function mountSound(locale) {
  const audio = createAudio({
    configUrl: '/assets/topdown/audio.json',
    presentation: PRESENTATION,
    biomeAt,
    assetsBase: '/',
    locale,
  });

  /* Движок вешает свою кнопку на body: там ей не место, её забирает правый
     верхний кластер. Разметку кнопки не трогаем — подпись добавляется рядом
     с иконкой, а состояние по-прежнему рисует сам движок через data-state. */
  const btn = audio.button;
  const label = document.createElement('span');
  label.className = 'snd__txt';
  label.textContent = locale === 'ru' ? 'Звук' : 'Sound';
  btn.appendChild(label);

  return {
    control: btn,
    update: (p) => audio.update(z(p)),
    state: () => audio.state(),
    hud: () => audio.hud(),
  };
}
